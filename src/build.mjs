// DashLink static site generator. Zero dependencies, Node 18+.
//
//   node src/build.mjs
//
// Reads every page in src/pages/*.mjs, renders it with src/components.mjs and
// writes <slug>/index.html at the site root. Also writes sitemap.xml, the
// /features/ redirect and docs/hero-variants.md.

import { readdir, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { layout, setContext } from './components.mjs';
import { SITE, STATIC_PAGES, APPS } from './config.mjs';
import { playUrl } from './play-url.mjs';

const SRC = dirname(fileURLToPath(import.meta.url));
const OUT = join(SRC, '..');
const VERSION = new Date().toISOString().slice(0, 16).replace(/\D/g, ''); // cache-buster for css/js

const files = (await readdir(join(SRC, 'pages'))).filter((f) => f.endsWith('.mjs')).sort();
const pages = [];
for (const f of files) {
  const page = (await import(pathToFileURL(join(SRC, 'pages', f)).href)).default;
  page.version = VERSION;
  pages.push(page);
}

async function write(rel, html) {
  const p = join(OUT, rel);
  await mkdir(dirname(p), { recursive: true });
  await writeFile(p, html);
}

const ids = new Map();
for (const page of pages) {
  const depth = page.slug ? page.slug.split('/').length : 0;
  setContext({ root: '../'.repeat(depth), key: page.key, pillar: page.pillar });
  const html = layout(page, page.body());
  // guard: anchor ids must be unique within a page
  const seen = new Set();
  for (const m of html.matchAll(/\sid="([^"]+)"/g)) {
    if (seen.has(m[1])) throw new Error(`${page.key}: duplicate id "${m[1]}"`);
    seen.add(m[1]);
  }
  ids.set(page.key, [...html.matchAll(/<(?:section|article) class="[^"]*" id="([^"]+)"/g)].map((m) => m[1]));
  await write(page.slug ? `${page.slug}/index.html` : 'index.html', html);
  console.log('built', '/' + (page.slug ? page.slug + '/' : ''));
}

/* /features/ was the old features page: send its anchors to the new pillars */
await write('features/index.html', `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="robots" content="noindex">
<title>DashLink features</title><link rel="canonical" href="${SITE.base}/dashboard/">
<script>(function(){var m={'#dock':'../dashboard/#dock','#care':'../trips-fuel-maintenance/#car-care','#fuel':'../trips-fuel-maintenance/#fuel','#home':'../android-auto/'};location.replace((m[location.hash]||'../dashboard/')+(m[location.hash]?'':location.hash)+'');})();</script>
<meta http-equiv="refresh" content="0; url=../dashboard/"></head><body style="background:#050506;color:#f4f6fb;font-family:system-ui;padding:40px">Moved to <a style="color:#5db6ff" href="../dashboard/">the Dashboard page</a>.</body></html>
`);

/* /pro/ became /plans/. GitHub Pages can't send a real 301, so this page
   redirects on the client and keeps the query string (UTMs, ?c=) and the hash
   (defaulting to #pro), with a canonical tag pointing at /plans/. */
await write('pro/index.html', `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="robots" content="noindex">
<title>DashLink plans</title><link rel="canonical" href="${SITE.base}/plans/">
<script>location.replace('../plans/'+location.search+(location.hash||'#pro'));</script>
<meta http-equiv="refresh" content="0; url=../plans/#pro"></head><body style="background:#050506;color:#f4f6fb;font-family:system-ui;padding:40px">Moved to <a style="color:#5db6ff" href="../plans/#pro">DashLink plans</a>.</body></html>
`);

/* sitemap */
const today = new Date().toISOString().slice(0, 10);
const urls = [...pages.map((p) => (p.slug ? p.slug + '/' : '')), ...STATIC_PAGES];
await write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${SITE.base}/${u}</loc><lastmod>${today}</lastmod></url>`).join('\n')}
</urlset>
`);

/* docs: hero-variant table + anchors per page */
let md = `# Hero variants and anchors\n\nGenerated by \`node src/build.mjs\` from \`src/pages/*.mjs\`. Don't edit by hand.\n\n` +
  `A variant is picked by \`?c=<key or alias>\`, or else when \`utm_campaign\` contains the key or an alias ` +
  `(lower-cased, with \`-\`, \`_\` and spaces removed). The first match in the order below wins. No match = default hero.\n\n`;
for (const p of pages) {
  const path = '/' + (p.slug ? p.slug + '/' : '');
  md += `## ${path}\n\n| Variant | Matches | Headline |\n|---|---|---|\n| *(default)* | — | ${clean(p.hero?.title || '')} |\n`;
  for (const [k, v] of Object.entries(p.hero?.variants || {})) {
    md += `| \`${k}\` | ${[...new Set([k, ...(v.match || [])])].map((m) => '`' + m + '`').join(', ')} | ${clean(v.title || '(default headline)')} |\n`;
  }
  md += `\nTry: \`${SITE.base}${path}?c=${Object.keys(p.hero?.variants || {})[0] || ''}\`\n\nAnchors: ${(ids.get(p.key) || []).filter((i) => i !== 'hero').map((i) => '`#' + i + '`').join(' ')}\n\n` +
    `Organic Play URL: \`${playUrl(p.playApp === 'wireless' ? APPS.wireless : APPS.headunit, p.key)}\`\n\n`;
}
await write('docs/hero-variants.md', md);
console.log('built docs/hero-variants.md, sitemap.xml, features/ and pro/ redirects');

function clean(s) { return String(s).replace(/<br\s*\/?>/g, ' ').replace(/<[^>]+>/g, '').replace(/&mdash;/g, '—').replace(/&amp;/g, '&').replace(/&nbsp;/g, ' ').replace(/\|/g, '\\|'); }
